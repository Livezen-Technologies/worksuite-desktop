const TABLES: Record<string, Table> = { en, si, ta, ar };

function lang(): string {
  return typeof document !== 'undefined' ? (document.documentElement.lang || 'en').split('-')[0]! : 'en';
}

export function tr(key: RKey, vars?: Record<string, string | number>): string {
  let s: string = TABLES[lang()]?.[key] ?? en[key] ?? humanise(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** A key made from the server's words (a tender, a mode) that has no string: its last part, readable. */
function humanise(key: string): string {
  const last = key.split('.').pop() ?? key;
  return last.charAt(0).toUpperCase() + last.slice(1).replace(/_/g, ' ');
}

/** `tr`, re-rendering the component when the language changes. */
export function useT(): typeof tr {
  useLanguage();
  return tr;
}
