const TABLES: Record<string, Partial<Record<PosKey, string>>> = { en, si, ta };

export function translate(lang: string, key: PosKey, vars?: Record<string, string | number>): string {
  let s: string = TABLES[lang]?.[key] ?? localize(en[key], lang);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** The till's strings in the person's language; re-renders when it changes. */
export function useT(): (key: PosKey, vars?: Record<string, string | number>) => string {
  const lang = useLanguage();
  return useCallback((key: PosKey, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
}
