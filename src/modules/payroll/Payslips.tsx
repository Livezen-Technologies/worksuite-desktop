import { useQuery } from '@tanstack/react-query';
import { useState, type KeyboardEvent } from 'react';
import { apiGet } from '../../core/api';
import { call, errorMessage } from '../../core/bridge';
import { toast } from '../../core/toasts';
import { Select } from '../../components/Select';
import { ErrorNote, Spinner, cx } from '../../components/ui';
import { groupLines, lineLabel, unsigned } from '../hr/pay';
import type { PayLine } from '../hr/api';
import { fetchRun, fetchRuns, runTitle, STATUS_LABEL } from './api';
import { Card, Kbd, Table, amt, td, tdr } from './parts';

/**
 * The payslip centre (D08): one approved run's payslips, a preview of the one selected (Space shows or hides it),
 * and the PDFs — one at a time, or all of them into the download folder. Payslips are generated by the server on
 * demand, never filed, so a corrected period never leaves a stale copy behind.
 */
const DONE = ['approved', 'locked', 'paying', 'paid'];

export default function Payslips({ runId, figures, onTemplate, onRun }: { runId: number | null; figures: boolean; onTemplate: () => void; onRun: (id: number) => void }) {
  const runs = useQuery({ queryKey: ['payroll', 'runs', 'payslips'], queryFn: ({ signal }) => fetchRuns('', 1, signal) });
  const ready = (runs.data?.items ?? []).filter((r) => DONE.includes(r.status));
  const id = runId ?? ready[0]?.id ?? null;
  const run = useQuery({ queryKey: ['payroll', 'run', id], queryFn: ({ signal }) => fetchRun(id!, signal), enabled: !!id });
  const [sel, setSel] = useState<number | null>(null);
  const [preview, setPreview] = useState(true);
  const slips = run.data?.payslips ?? [];
  const pick = slips.find((p) => p.id === sel) ?? slips[0] ?? null;
  const lines = useQuery({ queryKey: ['payroll', 'lines', pick?.id], queryFn: ({ signal }) => apiGet<{ lines: PayLine[] }>(`/api/payroll/payslips/${pick!.id}/lines`, undefined, signal), enabled: figures && !!pick && preview });
  const g = lines.data ? groupLines(lines.data.lines) : null;
  const r = run.data?.run;

  const pdf = async (pid: number, who: string, open: boolean) => {
    try {
      await call('transfers:download', { payrollDoc: { kind: 'run-payslip', id: String(pid) }, name: `Payslip ${r?.period_name ?? r?.id ?? ''} ${who}.pdf`.replace(/[/\\]/g, '-'), open });
    } catch (e) {
      toast('error', errorMessage(e));
    }
  };
  const all = async () => {
    for (const p of slips) await pdf(p.id, p.employee_no ?? String(p.id), false);
    toast('success', `${slips.length} payslips saved to your download folder.`);
  };
  const onKey = (e: KeyboardEvent) => {
    const i = slips.findIndex((p) => p.id === pick?.id);
    if (e.key === ' ') {
        e.preventDefault();
        setPreview((v) => !v);
      }
    else if (e.key === 'ArrowDown' && slips[i + 1]) {
        e.preventDefault();
        setSel(slips[i + 1]!.id);
      }
    else if (e.key === 'ArrowUp' && i > 0) {
        e.preventDefault();
        setSel(slips[i - 1]!.id);
      }
  };

  return (
    <div className="flex flex-col gap-3">
      <div className="flex flex-wrap items-end gap-2">
        <div className="min-w-0 flex-1">
          <h1 className="m-0 text-[21px] font-extrabold text-ink">Payslips</h1>
          {r ? <div className="mt-0.5 text-[12px] text-ink-2">{`${runTitle(r)} · ${STATUS_LABEL[r.status] ?? r.status}`}</div> : null}
        </div>
        <Select aria-label="Run" value={id ?? 0} onChange={(e) => onRun(Number(e.target.value))} className="h-8 rounded-[7px] border border-line bg-surface px-2 text-[12.5px] text-ink">
          {ready.map((x) => <option key={x.id} value={x.id}>{runTitle(x)}</option>)}
        </Select>
        <button type="button" className="h-8 rounded-[7px] border border-line bg-surface px-3 text-[12.5px] font-semibold text-ink" onClick={onTemplate}>Template</button>
        <button type="button" disabled={!figures || !slips.length} className="h-8 rounded-[7px] border border-line bg-surface px-3 text-[12.5px] font-semibold text-ink disabled:opacity-50" onClick={() => void all()}>Save all PDFs</button>
      </div>
      {runs.data && !ready.length ? <p className="m-0 text-[12.5px] text-ink-3">Payslips are made once a run is approved.</p> : null}
      {run.isLoading ? <Spinner /> : run.error ? <ErrorNote error={run.error} onRetry={() => void run.refetch()} /> : null}
      {slips.length ? (
        <div className="grid grid-cols-[minmax(0,1.3fr)_minmax(0,1fr)] items-start gap-2.5">
          <Card>
            <div tabIndex={0} role="grid" aria-label="Payslips" onKeyDown={onKey} className="outline-none">
              <Table head={['Employee', ['Net', 'r'], '']}>
                {slips.map((p) => (
                  <tr key={p.id} onClick={() => setSel(p.id)} aria-selected={p.id === pick?.id} className={cx('cursor-default', p.id === pick?.id ? 'bg-[#EEF1FD] dark:bg-selection' : 'hover:bg-subtle')}>
                    <td className={td}><b>{p.employee_name}</b> <span className="text-ink-2">{p.employee_no}</span></td>
                    <td className={tdr}>{figures ? amt(p.net) : '—'}</td>
                    <td className={tdr}>{figures ? <button type="button" className="font-semibold text-primary hover:underline" onClick={() => void pdf(p.id, p.employee_no ?? String(p.id), true)}>PDF</button> : null}</td>
                  </tr>
                ))}
              </Table>
            </div>
            <p className="m-0 px-3.5 py-2 text-[11px] text-ink-2"><Kbd>Space</Kbd> previews · <Kbd>↑↓</Kbd> moves</p>
          </Card>
          {preview && pick && figures ? (
            <section aria-label="Payslip preview" className="rounded-[10px] border border-line bg-surface px-4 py-3.5 text-[12px]">
              <div className="text-[11px] font-bold tracking-[.5px] text-ink-2 uppercase">{`Payslip · ${r?.period_name ?? ''}`}</div>
              <div className="text-[14px] font-bold text-ink">{`${pick.employee_name} · ${pick.employee_no ?? ''}`}</div>
              {lines.isLoading ? <Spinner /> : g ? (
                <div className="mt-2 flex flex-col gap-1">
                  {g.earnings.map((l, i) => <Row key={i} a={lineLabel(l)} b={amt(l.amount)} />)}
                  <Row a="Gross" b={amt(pick.gross)} strong />
                  {g.deductions.map((l, i) => <Row key={i} a={lineLabel(l)} b={`−${amt(unsigned(l.amount))}`} />)}
                  <Row a="Net pay" b={amt(pick.net, r?.currency ?? '')} strong />
                </div>
              ) : null}
            </section>
          ) : null}
        </div>
      ) : null}
    </div>
  );
}

const Row = ({ a, b, strong }: { a: string; b: string; strong?: boolean }) => (
  <div className={cx('flex justify-between', strong && 'border-t border-line pt-1 font-bold')}>
    <span>{a}</span>
    <span className="tabular-nums">{b}</span>
  </div>
);
